function report(ctx)
%REPORT Readable first-analysis results, using the same rows as exported CSVs.
c=ctx.cfg;A=ctx.summaries;
P=A(A.Sample=="primary_1ms"&A.Weighting=="pair",:);
pooled=P(P.Grouping=="pooled",:);
R=ctx.residuals(ctx.residuals.IsPrimary&ctx.residuals.Status=="OK",:);
lines=["# Planet orbital-product comparison run";"";"Profile: **"+c.profile+"**"];
if c.profile=="demo"
 lines=[lines;"";"**SYNTHETIC DEMONSTRATION: deterministic fixtures, not Planet measurements. SGP4 was not called.**"];
elseif c.profile=="pilot"
 lines=[lines;"";"**PILOT RESULTS: adopted frame interpretation and candidate identities require review before scientific use.**"];
end
lines=[lines;"";"Study dates: "+string(c.study.startUTC,'yyyy-MM-dd')+" to "+ ...
 string(c.study.endUTC,'yyyy-MM-dd')+" (inclusive, UTC)."; ...
 "SGP4 backend: `"+c.sgp4.backend+"`; Cartesian frame policy: `"+c.frames.cartesianMode+"`."; ...
 "Historical identity approval required: "+string(c.identity.requireHistoricalApproval)+"."; ...
 "Frame policy approved: "+string(c.frames.policyApproved)+ ...
 "; SGP4 verification approved: "+string(c.sgp4.verificationApproved)+"."; ...
 "";"## Workflow and sample";""; ...
 "Archives -> parse and deduplicate -> identity/time pairing -> evaluate the selected TLE at the Cartesian epoch -> common-frame differences -> RTN/ground metrics -> summaries and date-block uncertainty."; ...
 "";"| Sample count | Pairs |";"|---|---:|"; ...
 "| Primary accepted before evaluation | "+height(ctx.primary)+" |"; ...
 "| Primary successful for joint summaries | "+height(R)+" |"; ...
 "| Primary evaluation/metric exclusions | "+(height(ctx.primary)-height(R))+" |"; ...
 "| Separate 24 h accepted sample | "+height(ctx.wide)+" |"; ...
 "";"Primary uses native epoch separation at most 1 ms and at most one pair per satellite/UTC date. The 24 h sensitivity sample is summarized separately; it is not added to the primary results."; ...
 "All tables below use the same successful primary pairs, including successful ground conversion. See `failed_evaluations.csv` and `failed_metrics.csv` for excluded records."; ...
 "";poc.reporting.stageSummary(ctx); ...
 "";"## Stage 04 -- Evaluate the unchanged TLE and prepare common frames";""; ...
 "Evaluate the selected TLE at its paired Cartesian epoch, retain both prepared inertial states, and log identity, parsed-epoch and timing checks in `evaluated_states.csv`. The demo substitutes labelled deterministic fixtures for SGP4; no synthetic value is substituted for failed real propagation."; ...
 "Evaluation successes (union of selected samples): "+sum(ctx.evaluations.Status=="OK")+ ...
 "; failures: "+sum(ctx.evaluations.Status~="OK")+". Review `failed_evaluations.csv` before interpreting the retained sample."; ...
 "";"## Stage 05 -- Compute state, signed RTN and ground metrics";""; ...
 "Compute TLE-minus-Cartesian position/velocity differences, project position onto the Cartesian RTN basis, and calculate simultaneous WGS84 ground separation and signed geographic east/north components. `paired_residuals.csv` retains the per-pair metrics and failure messages."; ...
 "Successful joint metric rows (union of selected samples): "+sum(ctx.residuals.Status=="OK")+ ...
 "; failed metric rows: "+sum(ctx.residuals.Status~="OK")+". A ground failure excludes its pair from joint summaries but preserves any computed state metrics."];
if ~isempty(R)
 satellite=poc.reporting.selectGroundSatellite(ctx);
 nSatellite=sum(R.Satellite==satellite);
 lines=[lines;"";"### Latitude and longitude for one satellite";""; ...
  "Selected satellite: **"+escape(satellite)+"**, with "+nSatellite+" successful primary pairs. Unless a satellite was configured explicitly, this is the satellite with the most such pairs, with lexical name as the tie break."; ...
  "The coordinate figure compares simultaneous WGS84 ellipsoid-normal footpoints on the selected UTC pair dates. They are individual samples, not a continuous orbit or ground track; longitudes are wrapped to the displayed -180 to 180 degree range. Small separations may overlap at this scale: use the metre-based east/north figure to resolve them."; ...
  "Footpoints close across the -180/180 degree longitude boundary can appear at opposite chart edges; use the metre-based east/north figure to interpret their separation."];
 if c.reporting.figures
  lines=[lines;"";"![Latitude and longitude for the same selected satellite](figures/ground_satellite_latlon.png)"];
 end
end
lines=[lines;"";"## Stage 06 -- Summarize successful pairs and assess uncertainty";""; ...
 "Compute pair-weighted primary pooled/satellite/month statistics and separate sampling/weighting sensitivities. All components in each summary use the same successful pair set."];
if isempty(R)
 lines=[lines;"";"**No primary orbital-consistency result is available for this run.** Missing/NaN values do not represent zero discrepancy."];
end
lines=[lines;"";"### State and ground results";""; ...
 "Ground-distance RMS is in metres, with the paired-sample median and 95th percentile. Daily RMS pools the successful satellite pairs present on each UTC date; the daily table records their counts and includes only dates with successful observations. A daily RMS with one pair equals that pair's distance. The pooled RMS is calculated over pairs and is not an unweighted average of daily RMS values."; ...
 "| Metric | RMS | Median | 95th percentile | Unit |";"|---|---:|---:|---:|---|"];
if ~isempty(pooled)
 fields=["Position_m","Velocity_mps","Ground_m"];
 names=["3D position discrepancy","3D velocity discrepancy","WGS84 ground separation"];
 units=["m","m/s","m"];
 for k=1:3
  lines(end+1,1)="| "+names(k)+" | "+number(pooled.("RMS_"+fields(k))(1))+ ...
   " | "+number(pooled.("Median_"+fields(k))(1))+" | "+number(pooled.("Q95_"+fields(k))(1))+" | "+units(k)+" |"; %#ok<AGROW>
 end
end
lines=[lines;"";"### Signed east/north subsatellite displacement";""; ...
 "The Cartesian-derived WGS84 ellipsoid-normal footpoint is the local origin. At the same epoch, east and north components point toward the TLE-derived footpoint. Positive east points east; positive north points north. They are the inverse-geodesic distance times the sine and cosine of its initial azimuth, respectively, and are in metres."; ...
 "Each pair has its own local geographic axes. Near a geographic pole, the east/north orientation depends on the longitude used at the origin. The pooled means describe geographic offsets; inspect their variation across satellites and dates because opposite directions may cancel."; ...
 "";"| Component | Pairs | Signed mean (m) | Sample SD (m) | RMS (m) |";"|---|---:|---:|---:|---:|"];
components=["GroundEast","GroundNorth"];labels=["East","North"];
if ~isempty(pooled)
 for k=1:2
  a=components(k);
  lines(end+1,1)="| "+labels(k)+" | "+pooled.N(1)+" | "+number(pooled.("Mean_"+a+"_m")(1))+ ...
   " | "+number(pooled.("SD_"+a+"_m")(1))+" | "+number(pooled.("RMS_"+a+"_m")(1))+" |"; %#ok<AGROW>
 end
end
lines=[lines;"";"For each pair, ground separation squared equals east squared plus north squared by this distance-and-bearing convention. Geographic north is not the RTN orbital normal. These are relative subsatellite locations; they do not establish image-geolocation error or absolute accuracy."; ...
 "See [pooled east/north results](table6_ground_en_pooled.csv) and [all ground component groups, samples and weightings](table6_ground_en_all_groups.csv). The 24 h sample remains separately selected. Equal-satellite rows provide RMS values only; their means and SDs are not estimated."; ...
 "";"### RTN results";""; ...
 "Residual sign is **TLE minus Cartesian**. The Cartesian state defines R = r/|r|, N = (cross(r,v))/|cross(r,v)| and T = cross(N,R). Positive R points outward; positive T follows the transverse orbital direction; positive N follows the orbital angular momentum."; ...
 "";"| Component | Pairs | Signed mean (m) | Sample SD (m) | RMS (m) |";"|---|---:|---:|---:|---:|"];
axes=["R","T","N"];
if ~isempty(pooled)
 for k=1:3
  a=axes(k);
  lines(end+1,1)="| "+a+" | "+pooled.N(1)+" | "+number(pooled.("Mean_"+a+"_m")(1))+ ...
   " | "+number(pooled.("SD_"+a+"_m")(1))+" | "+number(pooled.("RMS_"+a+"_m")(1))+" |"; %#ok<AGROW>
 end
end
lines=[lines;"";"A signed mean describes a relative product offset. SD describes scatter about that mean (N-1 denominator); RMS includes offset and scatter. RMS(3D)^2 = RMS(R)^2 + RMS(T)^2 + RMS(N)^2, with no division by three. Neither product is an independent truth reference."; ...
 "";"#### RTN by satellite";""; ...
 "| Satellite | Pairs | Mean R (m) | Mean T (m) | Mean N (m) | RMS R (m) | RMS T (m) | RMS N (m) |"; ...
 "|---|---:|---:|---:|---:|---:|---:|---:|"];
S=P(P.Grouping=="satellite",:);
for k=1:height(S)
 lines(end+1,1)="| "+escape(S.Group(k))+" | "+S.N(k)+" | "+number(S.Mean_R_m(k))+ ...
  " | "+number(S.Mean_T_m(k))+" | "+number(S.Mean_N_m(k))+" | "+number(S.RMS_R_m(k))+ ...
  " | "+number(S.RMS_T_m(k))+" | "+number(S.RMS_N_m(k))+" |"; %#ok<AGROW>
end
lines=[lines;"";"Full satellite/month/component statistics: [table5_rtn_all_groups.csv](table5_rtn_all_groups.csv). The pooled table is also available as [table5_rtn_pooled.csv](table5_rtn_pooled.csv)."; ...
 "";"### Uncertainty";""; ...
 "Moving blocks sample calendar dates, keeping satellites on the same date together. Intervals describe uncertainty of summary statistics, not orbit covariance; their interpretation assumes suitable stationarity and dependence coverage."];
B=ctx.intervals;
if ~isempty(B)
 B=B(B.Grouping=="pooled"&B.BlockDays==c.bootstrap.blockDays(1)& ...
  ismember(B.Metric,["Mean_R_m","Mean_T_m","Mean_N_m","RMS_R_m","RMS_T_m","RMS_N_m", ...
   "Mean_GroundEast_m","Mean_GroundNorth_m","RMS_GroundEast_m","RMS_GroundNorth_m"]),:);
end
if isempty(B)
 lines=[lines;"";"No pooled RTN or east/north bootstrap interval was requested or produced. Descriptive point estimates above do not require a computed interval."];
else
 lines=[lines;"";"Primary block length: "+c.bootstrap.blockDays(1)+" days.";""; ...
  "| Position statistic (m) | Estimate | Lower 95% | Upper 95% | Valid replicates | Status |"; ...
  "|---|---:|---:|---:|---:|---|"];
 for k=1:height(B)
  lines(end+1,1)="| "+B.Metric(k)+" | "+number(B.Estimate(k))+" | "+number(B.Lower95(k))+ ...
   " | "+number(B.Upper95(k))+" | "+B.ValidReplicates(k)+"/"+B.Replicates(k)+" | "+B.Status(k)+" |"; %#ok<AGROW>
 end
end
lines=[lines;"";"All block lengths and groups are in [bootstrap_intervals.csv](bootstrap_intervals.csv). NaN means missing support or an unavailable statistic, never zero discrepancy. Sample SD is NaN for a single pair."; ...
 "";"## Stage 07 -- Export results, figures and provenance";""; ...
 "Export the tables below, MATLAB results structure and figures. The stage ledger is finalized after this export completes: inspect `stage_log.csv` and the `RUN_COMPLETE.txt` marker before treating the run as complete."];
if c.reporting.figures&&~isempty(R)
 lines=[lines;"";"### Figures";""; ...
  "Ground plots use the successful primary pairs; each daily RMS summarizes the pairs available on that UTC date. Individual observations are not interpolated. SD whiskers describe sample scatter and are not confidence intervals."; ...
  "";"![WGS84 geodesic separation of individual pairs by UTC date](figures/daily_Ground_m.png)"; ...
  "";"![Daily pooled WGS84 ground-distance RMS and sample counts](figures/ground_daily_rms.png)"; ...
  "";"![WGS84 ground-distance RMS by satellite](figures/ground_satellite_rms.png)"; ...
  "";"![Empirical distribution of WGS84 ground distances](figures/ground_ecdf.png)"; ...
  "";"![Signed local east and north subsatellite offsets](figures/ground_en_scatter.png)"; ...
  "";"![Signed east and north subsatellite offsets by UTC pair date](figures/ground_en_daily.png)"; ...
  "";"![Cartesian-derived footpoint locations coloured by ground separation](figures/ground_locations.png)"; ...
  "";"![Signed RTN residuals by UTC pair date](figures/rtn_daily.png)"; ...
  "";"![Pooled RTN signed means, sample SD and RMS](figures/rtn_summary.png)"; ...
  "";"![Three-dimensional position discrepancy by UTC pair date](figures/daily_Position_m.png)"; ...
  "";"PNG figures have editable MATLAB FIG companions in `figures/`."];
end
lines=[lines;"";"### Files to inspect";""; ...
 "| File | Contents |";"|---|---|"; ...
 "| [table3_coverage.csv](table3_coverage.csv) | Full-roster coverage, including satellites with no pairs |"; ...
 "| [table4_pooled_state_ground.csv](table4_pooled_state_ground.csv) | Primary pooled vector and ground statistics |"; ...
 "| [ground_daily_summary.csv](ground_daily_summary.csv), [ground_satellite_summary.csv](ground_satellite_summary.csv) | Ground distance RMS, median and 95th percentile with daily/satellite pair counts |"; ...
 "| [table6_ground_en_pooled.csv](table6_ground_en_pooled.csv), [all groups](table6_ground_en_all_groups.csv) | Signed east/north means, sample SD and RMS |"; ...
 "| [paired_residuals.csv](paired_residuals.csv) | Per-pair signed RTN, vector/ground metrics and status |"; ...
 "| [summary_all.csv](summary_all.csv) | Primary, separate 24 h, asynchronous-only, weekly and weighting sensitivities |"; ...
 "| [bootstrap_intervals.csv](bootstrap_intervals.csv) | Interval estimates, support counts and status |"; ...
 "| `run_manifest.json`, `results.mat`, `stage_*.mat` | Configuration, provenance and recoverable MATLAB stage data |"; ...
 "| [stage_log.csv](stage_log.csv), `RUN_COMPLETE.txt` | Per-stage status/timing and whole-run completion marker |"];
poc.io.writeText(fullfile(ctx.runDir,'RUN_REPORT.md'),strjoin(lines,newline)+newline);
end
function s=number(x)
if isnan(x),s="NaN";else,s=string(sprintf('%.6g',x));end
end
function s=escape(s)
s=replace(string(s),"|","\|");s=replace(s,newline," ");
end
