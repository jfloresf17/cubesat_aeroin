function lines=stageSummary(ctx)
%STAGESUMMARY Source and pairing diagnostics shared by complete/audit reports.
% Missing optional context is labelled unavailable, never converted to zero.
c=ctx.cfg;
lines=["## Stage 00 -- Preflight and configuration";""; ...
 "The MATLAB integrator freezes the configuration, checks the reviewed time window and required dependencies, and creates a new run directory."; ...
 "Configuration: `configuration.mat`; environment, versions and source/configuration hashes: `run_manifest.json`."; ...
 "Profile: **"+c.profile+"**; study dates: "+string(c.study.startUTC,'yyyy-MM-dd')+ ...
 " through "+string(c.study.endUTC,'yyyy-MM-dd')+" (inclusive UTC)."; ...
 "";"## Stage 01 -- Acquire and verify source archives";""; ...
 "Dated Cartesian/TLE archives are cached without replacing existing payloads. Guard dates support nearest-epoch selection at study boundaries. Source-file checksums and download/cache status are recorded in `archive_manifest.csv`."; ...
 "";"| Archive check | Count |";"|---|---:|"];
if isfield(ctx,'manifest')
 M=ctx.manifest;ok=ismember(M.Status,["CACHED","DOWNLOADED"]);
 lines=[lines;"| Manifest entries | "+height(M)+" |"; ...
  "| Usable cached/downloaded entries | "+sum(ok)+" |"; ...
  "| Missing, failed or checksum-mismatched entries | "+sum(~ok)+" |"];
else
 lines=[lines;"| Manifest counts | not recorded in this context |"];
end
lines=[lines;"";"Review unavailable source files before interpreting coverage; missing archives are not filled with present-day or synthetic products."; ...
 "";"## Stage 02 -- Parse, reconcile time and clean records";""; ...
 "Native epochs are represented as integer TT nanoseconds. Identical repeated payloads are deduplicated while their archive occurrences remain recorded. All conflicting payloads at one identity/native epoch are flagged and excluded from pairing."; ...
 "";"| Preprocessing check | Count |";"|---|---:|"; ...
 "| Unique Cartesian payloads, including flagged revisions | "+rowCount(ctx,'states')+" |"; ...
 "| Unique TLE payloads, including flagged revisions | "+rowCount(ctx,'tles')+" |"; ...
 "| Recorded source occurrences | "+rowCount(ctx,'occurrences')+" |"; ...
 "| Cartesian conflicting revisions | "+sumColumn(ctx,'states','Revision')+" |"; ...
 "| TLE conflicting revisions | "+sumColumn(ctx,'tles','Revision')+" |"; ...
 "| Parse-log entries | "+rowCount(ctx,'parseLog')+" |"; ...
 "";"Inspect `states.csv`, `tles.csv`, `record_occurrences.csv`, `parse_log.csv` and `time_precision_audit.csv`. Parse-log entries can include records outside the target input format; examine the recorded code and message before attributing them to the target cohort."; ...
 "";"## Stage 03 -- Identity checks and native-epoch pairing";""; ...
 "Match the roster catalogue identity and TLE-header HWID within the roster validity interval. For each state, choose the nearest eligible TLE, favouring its earlier epoch on a tie. Retain the latest eligible Cartesian state per satellite/UTC day."; ...
 "The primary window is at most "+string(double(c.pairing.primaryTolerance_ns)/1e6)+ ...
 " ms. The independently selected sensitivity window is at most "+ ...
 string(double(c.pairing.sensitivityTolerance_ns)/3.6e12)+" h; it never enlarges the primary sample."; ...
 "";"| Pairing check | Count |";"|---|---:|"; ...
 "| Primary candidate decisions | "+rowCount(ctx,'primaryCandidates')+" |"; ...
 "| Selected primary daily pairs | "+rowCount(ctx,'primary')+" |"; ...
 "| Selected separate wide-window daily pairs | "+rowCount(ctx,'wide')+" |"; ...
 "";"Inspect `coverage.csv`, `roster_used.csv`, both `*_candidate_decisions.csv` tables and `primary_pairs.csv` / `sensitivity_pairs.csv`. Selection uses identity and time, never the measured residual."];
end
function s=rowCount(ctx,name)
if isfield(ctx,name),s=string(height(ctx.(name)));else,s="not recorded";end
end
function s=sumColumn(ctx,name,column)
if isfield(ctx,name)&&ismember(string(column),string(ctx.(name).Properties.VariableNames))
 s=string(sum(ctx.(name).(column)));
else
 s="not recorded";
end
end
