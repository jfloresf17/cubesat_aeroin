function latestPath=publishLatest(ctx)
%PUBLISHLATEST Publish a complete run's report at the results root.
% The original run directory remains unchanged. Local Markdown links are
% rebased to that directory; external, root-relative and anchor links remain.
assert(isfield(ctx,'runDir')&&isfield(ctx,'cfg')&&isfield(ctx,'stageLog'), ...
 'poc:report:LatestContext','A completed run context is required.');
assert(istable(ctx.stageLog)&&ismember("Status",string(ctx.stageLog.Properties.VariableNames)) ...
 &&~isempty(ctx.stageLog)&&all(ctx.stageLog.Status=="COMPLETE"), ...
 'poc:report:LatestIncomplete','Every configured stage must complete before publication.');
runDir=string(ctx.runDir);
assert(isfile(fullfile(runDir,'RUN_COMPLETE.txt')), ...
 'poc:report:LatestIncomplete','The run completion marker is missing.');
sourcePath=fullfile(runDir,'RUN_REPORT.md');
assert(isfile(sourcePath),'poc:report:LatestMissing','The completed run has no report: %s',sourcePath);
sourceText=fileread(sourcePath);
assert(~isempty(strtrim(sourceText)),'poc:report:LatestEmpty', ...
 'The completed run report is empty: %s',sourcePath);
source=string(sourceText);
[parent,name,ext]=fileparts(runDir);runName=name+ext;
assert(strlength(runName)>0&&isfolder(parent),'poc:report:LatestPath', ...
 'The completed run must be inside an existing results directory.');
latestPath=fullfile(parent,'RUN_REPORT.md');
marker="<!-- Generated by poc.reporting.publishLatest -->";
assert(~isfolder(latestPath),'poc:report:LatestUnowned', ...
 'The latest-report path is an existing directory: %s',latestPath);
hadLatest=isfile(latestPath);previousHash="";
if hadLatest
 checkOwnedWritable(latestPath,marker);
 previousHash=poc.io.hashFile(latestPath);
end
prefix=replace(runName,"%","%25");
prefix=replace(prefix," ","%20");prefix=replace(prefix,"#","%23");
prefix=replace(prefix,"?","%3F");prefix=replace(prefix,"(","%28");
prefix=replace(prefix,")","%29");
created=string(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss''Z'''));
c=ctx.cfg;
header=[marker;"# Latest MATLAB analysis";""; ...
 "Run: `"+runName+"`; profile: **"+c.profile+"**."; ...
 "Study dates: "+string(c.study.startUTC,'yyyy-MM-dd')+" through "+ ...
 string(c.study.endUTC,'yyyy-MM-dd')+" (inclusive UTC)."; ...
 "Published UTC: "+created+"."; ...
 "[Open the original run report]("+prefix+"/RUN_REPORT.md)";"";"---";""];
body=rebaseLinks(source,prefix);
temporary=string(tempname(parent))+".tmp";
cleanup=onCleanup(@()removeTemporary(temporary)); %#ok<NASGU>
poc.io.writeText(temporary,strjoin(header,newline)+newline+body);
% Refuse to replace a report that appeared or changed while preparing output.
if hadLatest
 assert(isfile(latestPath),'poc:report:LatestChanged', ...
  'The previous latest report disappeared during publication.');
 checkOwnedWritable(latestPath,marker);
 assert(poc.io.hashFile(latestPath)==previousHash,'poc:report:LatestChanged', ...
  'The previous latest report changed during publication.');
else
 assert(~isfile(latestPath)&&~isfolder(latestPath),'poc:report:LatestChanged', ...
  'Another item appeared at the latest-report path during publication.');
end
[ok,msg]=movefile(temporary,latestPath,'f');
assert(ok,'poc:report:LatestWrite','Could not publish latest report: %s',msg);
end
function body=rebaseLinks(source,prefix)
% Ignore fenced and inline code; links to anchors, URLs and absolute paths
% keep their original meaning. Preserve links to ../ as run-relative paths.
lines=splitlines(source);fence="";fenceLength=0;
for j=1:numel(lines)
 line=lines(j);
 marker=regexp(char(line),'^\s*(`{3,}|~{3,})','tokens','once');
 if ~isempty(marker)
  m=string(marker{1});
  if fence=="",fence=extractBefore(m,2);fenceLength=strlength(m);
  elseif startsWith(m,fence)&&strlength(m)>=fenceLength,fence="";fenceLength=0;end
 elseif fence==""
  lines(j)=rebaseLine(line,prefix);
 end
end
body=strjoin(lines,newline);
end
function out=rebaseLine(line,prefix)
rawLine=char(line);
[starts,ends,tokens]=regexp(rawLine,'(!?\[[^\]\r\n]*\]\()([^\)\r\n]*)(\))', ...
 'start','end','tokens');
out="";cursor=1;
for k=1:numel(starts)
 if cursor<starts(k),out=out+string(rawLine(cursor:starts(k)-1));end
 parts=tokens{k};target=asString(parts{2});
 if ~insideCode(rawLine,starts(k)),target=rebaseTarget(target,prefix);end
 out=out+string(parts{1})+target+string(parts{3});
 cursor=ends(k)+1;
end
if cursor<=numel(rawLine),out=out+string(rawLine(cursor:end));end
end
function target=rebaseTarget(target,prefix)
% Preserve optional link titles and angle brackets used for paths with spaces.
t=regexp(char(target),'^(\s*)<([^>]*)>(.*)$','tokens','once');
if ~isempty(t)
 path=asString(t{2});
 if isLocal(path),target=asString(t{1})+"<"+prefix+"/"+path+">"+asString(t{3});end
 return;
end
t=regexp(char(target),'^(\s*)(\S+)(.*)$','tokens','once');
if isempty(t),return;end
path=string(t{2});
if isLocal(path),target=asString(t{1})+prefix+"/"+path+asString(t{3});end
end
function tf=isLocal(path)
tf=strlength(path)>0&&~any(startsWith(path,["#","/","\"]),'all') ...
 &&isempty(regexp(char(path),'^[A-Za-z][A-Za-z0-9+.-]*:','once'));
end
function tf=insideCode(line,stop)
% Backtick spans are not links, even if they contain Markdown-like text.
i=1;delimiter=0;
while i<stop
 if line(i)=='`'&&(i==1||line(i-1)~='\')
  j=i;while j<stop&&line(j)=='`',j=j+1;end
  count=j-i;
  if delimiter==0,delimiter=count;elseif delimiter==count,delimiter=0;end
  i=j;
 else
  i=i+1;
 end
end
tf=delimiter>0;
end
function removeTemporary(path)
if isfile(path),delete(path);end
end
function checkOwnedWritable(path,marker)
existing=fileread(path);
assert(~isempty(existing)&&startsWith(string(existing),marker),'poc:report:LatestUnowned', ...
 'The existing report was not generated by the latest-report publisher: %s',path);
[ok,attributes]=fileattrib(path);
assert(ok&&isscalar(attributes)&&isfield(attributes,'UserWrite') ...
 &&isfinite(attributes.UserWrite)&&attributes.UserWrite==1, ...
 'poc:report:LatestReadOnly','The existing latest report is not writable: %s',path);
end
function s=asString(text)
if isempty(text),s="";else,s=string(text);end
end
