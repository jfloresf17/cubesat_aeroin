function C=coverage(ctx)
%COVERAGE Complete roster counts, including satellites with no valid pairs.
R=ctx.roster;rows=struct([]);sats=unique(R.Satellite,'stable');
for k=1:numel(sats)
 rr=R(R.Satellite==sats(k),:);h=unique(rr.HWID);
 S=ctx.states(ismember(ctx.states.HWID,h),:);
 S=S(S.EpochUTC>=ctx.cfg.study.startUTC & S.EpochUTC<ctx.cfg.study.endUTC+caldays(1),:);
 P=ctx.primary(ctx.primary.Satellite==sats(k),:);
 W=ctx.wide(ctx.wide.Satellite==sats(k),:);
 D=ctx.primaryCandidates(ismember(ctx.primaryCandidates.HWID,h),:);
 week=poc.pairing.weekly(P);
 z=struct('Satellite',sats(k),'CandidateHWIDs',strjoin(h,";"), ...
  'HistoricalApproval',all(rr.HistoricallyVerified),'UniqueStateRecords',height(S), ...
  'StateDates',numel(unique(dateshift(S.EpochUTC,'start','day'))), ...
  'ConflictingStateRecords',sum(S.Revision),'RepeatedStateOccurrences',sum(S.DuplicateOccurrences), ...
  'DailyPairs',height(P),'VerifiedDailyPairs',sum(P.IdentityVerified), ...
  'DistinctPairDates',numel(unique(P.DateUTC)),'WeeklyPairs',height(week), ...
  'WideWindowPairs',height(W),'AsyncOnlyPairs',sum(abs(W.DeltaTime_ns)>ctx.cfg.pairing.primaryTolerance_ns), ...
  'RejectedOrUnselectedStates',sum(D.Status~="ACCEPTED"), ...
  'MedianAbsDelta_s',poc.stats.quantile(abs(P.DeltaTime_s),0.5), ...
  'Q95AbsDelta_s',poc.stats.quantile(abs(P.DeltaTime_s),0.95));
 if isempty(rows),rows=z;else,rows(end+1,1)=z;end %#ok<AGROW>
end
C=struct2table(rows);
end
