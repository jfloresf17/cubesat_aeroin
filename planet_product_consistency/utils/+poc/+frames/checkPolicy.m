function checkPolicy(cfg)
%CHECKPOLICY Explicit gates: never silently declare J2000 equivalent to ICRF.
assert(cfg.frames.cartesianMode~="unresolved",'poc:frame:Unresolved', ...
 ['Review the Cartesian J2000-to-ICRF convention. Set an explicit mode and ' ...
  'document the evidence in cfg.frames.evidence.']);
if cfg.profile=="research"
 assert(cfg.frames.policyApproved && strlength(cfg.frames.evidence)>0, ...
  'poc:frame:Approval','Research mode requires a reviewed frame policy and evidence.');
 assert(cfg.sgp4.verificationApproved&&strlength(cfg.sgp4.verificationEvidence)>0, ...
  'poc:sgp4:Verification','Record local SGP4 verification before research evaluation.');
 assert(cfg.sgp4.backend=="matlab",'poc:sgp4:Backend','Research backend must be MATLAB SGP4.');
 assert(~ismember(cfg.frames.earthMode,["synthetic_identity","zero_eop_pilot"]), ...
  'poc:frame:EOP','Research mode prohibits synthetic/zero-EOP ground conversion.');
end
if cfg.sgp4.backend=="synthetic_fixture"
 assert(cfg.profile=="demo",'poc:sgp4:Synthetic','Synthetic backend is demo-only.');
else
 assert(ismember(exist('propagateOrbit','file'),[2 3 6]) && ...
  ismember(exist('tleread','file'),[2 3 6]), ...
  'poc:environment:Aerospace','Requires Aerospace Toolbox with propagateOrbit (R2024b+).');
end
end
