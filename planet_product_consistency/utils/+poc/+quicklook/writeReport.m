function writeReport(runDir,opts,inventory,stats,windows,matches,sceneStatus,previews)
%WRITEREPORT Write a human-readable inventory and local preview gallery.
totalDays=height(inventory.Daily);
stateDays=sum(inventory.Daily.StateArchiveAvailable);
tleDays=sum(inventory.Daily.TLEArchiveAvailable);
badFiles=sum(~ismember(inventory.Files.Status,["LOADED","DUPLICATE_COPY","IGNORED_NAME"]));
[ids,~,matchGroup]=unique(matches.SceneID);sceneN=numel(ids);
if isempty(previews),previewN=0;else,previewN=sum(ismember(previews.ThumbnailStatus,["DOWNLOADED","EXISTS"]));end
if isempty(previews),pendingN=0;else,pendingN=sum(previews.ThumbnailStatus=="PENDING");end
startText=string(opts.StartUTC,'yyyy-MM-dd');
endText=string(opts.EndUTC,'yyyy-MM-dd');
lines=["# PlanetScope acquisition quick look";""; ...
 "This is an exploratory catalogue inventory, not an orbital or image-accuracy result."; ...
 ""; "## Search and matching";""; ...
 "- UTC acquisition dates: "+startText+" through "+endText+" (inclusive)."; ...
 "- Scene-to-Cartesian tolerance: "+opts.TimeToleranceSeconds+" seconds (inclusive)."; ...
 "- TLE filter: native TLE UTC epoch must be on the scene's UTC date; no 1 ms TLE filter."; ...
 "- Matching uses native satellite IDs/header HWIDs and retains every qualifying state/TLE combination."; ...
 "- Identity is candidate unless independently verified; roster conflicts remain explicitly flagged."; ...
 "- API searched merged windows around local states, not all scenes in the calendar year."; ...
 "- Reported acquisition timestamps are catalogue timestamps; centre-line timing is not certified."; ...
 ""; "## Coverage";""; ...
 "| Measure | Count |";"|---|---:|"; ...
 "| Requested UTC calendar dates | "+totalDays+" |"; ...
 "| Dates with a loaded state archive | "+stateDays+" |"; ...
 "| Dates with a loaded TLE archive | "+tleDays+" |"; ...
 "| Archives flagged for inspection | "+badFiles+" |"; ...
 "| Parsed local states in scope | "+inventory.StateCount+" |"; ...
 "| Parsed local TLEs in scope | "+inventory.TLECount+" |"; ...
 "| Merged acquisition search windows | "+size(windows,1)+" |"; ...
 "| Planet API searches / pages | "+stats.Searches+" / "+stats.Pages+" |"; ...
 "| Candidate scenes returned in search windows | "+height(sceneStatus)+" |"; ...
 "| Matched unique scenes | "+sceneN+" |"; ...
 "| Matching scene-state-TLE combinations | "+height(matches)+" |"; ...
 "| Downloaded scene previews | "+previewN+" |"; ...
 "| Previews awaiting download | "+pendingN+" |"; ...
 "| Parse-log entries | "+height(inventory.ParseLog)+" |"; ...
 ""; "## Files";""; ...
 "- [Preview gallery](index.html) shows one card per matched scene and its matching records."; ...
 "- [matches.csv](matches.csv) retains every matching combination, scene metadata and native provenance."; ...
 "- [candidate_scenes.csv](candidate_scenes.csv) and [scene_status.csv](scene_status.csv) show searched candidates and match outcomes."; ...
 "- [preview_status.csv](preview_status.csv) records preview availability; previews are not full-resolution imagery."; ...
 "- PENDING previews have not yet completed; match tables are already available."; ...
 "- [archive_coverage.csv](archive_coverage.csv), [archive_inventory.csv](archive_inventory.csv) and [parse_log.csv](parse_log.csv) document local source coverage."; ...
 "- quicklook_results.mat retains the MATLAB tables and options without credentials."; ...
 ""; "Absence of a match is conditional on the accessible catalogue, local archive coverage, source parsing, identity and the time tolerance. It is not evidence that no image was acquired."; ...
 "No orbital evaluation, independent position validation or image-geolocation error is calculated."];
poc.io.writeText(fullfile(runDir,'QUICKLOOK_REPORT.md'),strjoin(lines,newline)+newline);

html=["<!doctype html>";'<html lang="en"><head><meta charset="utf-8">'; ...
 '<meta name="viewport" content="width=device-width, initial-scale=1">'; ...
 '<title>PlanetScope acquisition quick look</title>'; ...
 '<style>body{font:15px system-ui,sans-serif;max-width:1100px;margin:2em auto;padding:0 1em;color:#1b2a39}'; ...
 'h1,h2{color:#123859} .card{border:1px solid #cedae4;border-radius:8px;padding:1em;margin:1em 0;overflow:auto}'; ...
 'img{max-width:256px;max-height:256px;float:left;margin:0 1em 1em 0} table{border-collapse:collapse;width:100%}'; ...
 'td,th{text-align:left;padding:.35em;border-bottom:1px solid #dce4e9;vertical-align:top}'; ...
 '.muted{color:#556b7b} code{overflow-wrap:anywhere} .clear{clear:both}</style></head><body>'; ...
 '<h1>PlanetScope acquisition quick look</h1>'; ...
 '<p>UTC '+startText+' to '+endText+'; tolerance '+string(opts.TimeToleranceSeconds)+' s. '; ...
 string(sceneN)+' matched scenes and '+string(height(matches))+' scene–state–TLE combinations.</p>'; ...
 '<p class="muted">Candidate identity and catalogue timing require review. '; ...
 'A same-day TLE means its native epoch is on the scene UTC date.</p>'; ...
 '<p><a href="QUICKLOOK_REPORT.md">Run report</a> · <a href="matches.csv">All matches (CSV)</a> · '; ...
 '<a href="scene_status.csv">Scene status (CSV)</a> · <a href="archive_coverage.csv">Archive coverage (CSV)</a></p>'];
if isempty(matches)
 html(end+1)='<p>No matched scenes were found for the available inputs and selected tolerance.</p>';
else
 % Group matches once rather than scanning both tables for every scene.
 % sort is stable, preserving the original combination order within a card.
 [~,matchOrder]=sort(matchGroup);
 groupCounts=accumarray(matchGroup,1,[sceneN,1]);
 groupEnds=cumsum(groupCounts);
 [~,previewIndex]=ismember(ids,previews.SceneID);
 cards=strings(sceneN,1);
 for k=1:numel(ids)
  first=groupEnds(k)-groupCounts(k)+1;
  m=matches(matchOrder(first:groupEnds(k)),:);
  card='<section class="card"><h2>'+escapeHTML(ids(k))+'</h2>';
  q=previewIndex(k);
  if q>0 && ismember(previews.ThumbnailStatus(q),["DOWNLOADED","EXISTS"]) && ...
    strlength(previews.ThumbnailLocalPath(q))>0
   path=replace(previews.ThumbnailLocalPath(q),string(filesep),"/");
   card(end+1)='<img src="'+escapeHTML(path)+'" alt="Planet scene preview">'; %#ok<AGROW>
  elseif q>0
   card(end+1)='<p class="muted">Preview: '+escapeHTML(previews.ThumbnailStatus(q))+'</p>'; %#ok<AGROW>
  end
  card(end+1)='<p><b>Satellite:</b> '+escapeHTML(m.SatelliteID(1))+' &nbsp; <b>Strip:</b> '+escapeHTML(m.StripID(1))+'</p>'; %#ok<AGROW>
  card(end+1)='<p><b>Acquired UTC:</b> '+escapeHTML(string(m.AcquiredUTC(1),'yyyy-MM-dd HH:mm:ss.SSSSSS'))+'</p>'; %#ok<AGROW>
  card(end+1)='<p><b>View angle:</b> '+escapeHTML(string(m.ViewAngle_deg(1)))+'° &nbsp; <b>Satellite azimuth:</b> '+escapeHTML(string(m.SatelliteAzimuth_deg(1)))+'°</p>'; %#ok<AGROW>
  card(end+1)='<p><b>Quality:</b> '+escapeHTML(m.QualityCategory(1))+' &nbsp; <b>Ground control:</b> '+escapeHTML(string(m.GroundControl(1)))+' &nbsp; <b>Cloud cover:</b> '+escapeHTML(string(m.CloudCover(1)))+'</p>'; %#ok<AGROW>
  if strlength(m.ItemURL(1))>0
   card(end+1)='<p><a href="'+escapeHTML(m.ItemURL(1))+'">Planet item metadata</a></p>'; %#ok<AGROW>
  end
  card(end+1)='<div class="clear"></div><details><summary>'+string(height(m))+' matching combination(s)</summary>'; %#ok<AGROW>
  card(end+1)='<table><tr><th>State epoch UTC</th><th>Scene − state (s)</th><th>TLE epoch UTC</th><th>Identity</th></tr>'; %#ok<AGROW>
  for j=1:height(m)
   card(end+1)='<tr><td>'+escapeHTML(string(m.StateEpochUTC(j),'yyyy-MM-dd HH:mm:ss.SSSSSS'))+ ...
    '</td><td>'+escapeHTML(string(m.SceneMinusState_s(j)))+ ...
    '</td><td>'+escapeHTML(string(m.TLEEpochUTC(j),'yyyy-MM-dd HH:mm:ss.SSSSSS'))+ ...
    '</td><td>'+escapeHTML(m.IdentityStatus(j))+'</td></tr>'; %#ok<AGROW>
  end
  card(end+1)='</table></details></section>'; %#ok<AGROW>
  cards(k)=strjoin(card,newline);
 end
 html=[html;cards];
end
html(end+1)='</body></html>';
poc.io.writeText(fullfile(runDir,'index.html'),strjoin(html,newline)+newline);
end

function s=escapeHTML(value)
s=string(value);
if ismissing(s),s="";end
s=replace(s,"&","&amp;");
s=replace(s,"<","&lt;");
s=replace(s,">","&gt;");
s=replace(s,'"',"&quot;");
s=replace(s,"'","&#39;");
end
